defmodule EctoRust.Native do
  @moduledoc """
  Writes the two files that make the Phoenix app run the Rust of its
  `@universal_changeset true` functions, and that exist only while one is
  marked, so a repository without a mark never needs the Rust toolchain:

    * `lib/app/data/universal_changeset/native.ex`,
      `App.Data.UniversalChangeset.Native`: `use Rustler`, which compiles
      the NIF crate during `mix compile`, `run/4` and `cast/2` for each
      function, and a stub per NIF
    * `native/universal_changeset/src/lib.rs`: the crate, including the
      `.rs` next to each schema by path and exporting one NIF per function
  """

  alias EctoRust.{Source, Transpile}

  @elixir_path "lib/app/data/universal_changeset/native.ex"
  @rust_path "native/universal_changeset/src/lib.rs"

  def elixir_path, do: @elixir_path
  def rust_path, do: @rust_path

  @doc """
  The NIF name of a marked function: the schema's name and the function's.
  """
  def nif(%Source{module: module, function: function}), do: :"#{schema(module)}_#{function}"

  @doc """
  `App.Data.UniversalChangeset.Native` for the marked functions, as
  `{:ok, source}`.
  """
  def elixir(sources) do
    files = sources |> Enum.map(& &1.file) |> Enum.uniq() |> Enum.sort()

    runs =
      Enum.map_join(sources, "\n", fn source ->
        "def run(#{inspect(source.module)}, #{inspect(source.function)}, data, params), do: #{nif(source)}(data, params)"
      end)

    casts =
      Enum.map_join(sources, "\n", fn source ->
        {:ok, [%{cast: cast}]} = Transpile.functions([source])
        "def cast(#{inspect(source.module)}, #{inspect(source.function)}), do: #{inspect(cast)}"
      end)

    stubs =
      Enum.map_join(sources, "\n\n", fn source ->
        "def #{nif(source)}(_data, _params), do: :erlang.nif_error(:nif_not_loaded)"
      end)

    source = """
    defmodule App.Data.UniversalChangeset.Native do
      @moduledoc \"\"\"
      Generated by `mix app.rust`: the Rust of every changeset function marked
      `@universal_changeset true`, compiled into the Phoenix app as a NIF. Do
      not edit: it is written while a function is marked and removed when
      none is, so only a marked function makes `mix compile` need the Rust
      toolchain.
      \"\"\"

      # The Rust next to each schema is compiled in by path, so a change to
      # it recompiles this module and with it the crate
    #{Enum.map_join(files, "\n", &"  @external_resource #{inspect(rust_file(&1))}")}

      use Rustler, otp_app: :app, crate: "universal_changeset"

      @doc \"\"\"
      Runs the Rust of a marked function: the data and the params go in as
      JSON, the errors come out as JSON.
      \"\"\"
    #{indent(runs)}

      @doc \"\"\"
      The fields a marked function casts, which `App.Data.UniversalChangeset.run/3`
      tells apart from the fields the app sets.
      \"\"\"
    #{indent(casts)}

    #{indent(stubs)}
    end
    """

    {:ok, Code.format_string!(source) |> IO.iodata_to_binary() |> Kernel.<>("\n")}
  end

  @doc """
  The NIF crate's `lib.rs` for the marked functions, as `{:ok, source}`.
  """
  def rust(sources) do
    modules =
      sources
      |> Enum.map(&{schema(&1.module), rust_file(&1.file)})
      |> Enum.uniq()
      |> Enum.sort()
      |> Enum.map_join("\n\n", fn {name, file} ->
        """
        #[allow(dead_code)]
        #[path = "../../../#{file}"]
        mod #{name};
        """
      end)

    nifs =
      Enum.map_join(sources, "\n\n", fn source ->
        """
        #[rustler::nif]
        fn #{nif(source)}(data: &str, params: &str) -> NifResult<String> {
            run(data, params, #{schema(source.module)}::#{source.function})
        }
        """
      end)

    source = """
    //! Generated by `mix app.rust`: the NIF behind `App.Data.UniversalChangeset.Native`.
    //! Do not edit: it is written while a changeset function is marked
    //! `@universal_changeset true` and removed when none is. Each NIF takes
    //! the data and the params as JSON and returns the errors as JSON, from
    //! the Rust next to the schema, which the other apps compile in too.

    use ecto_changeset::{Changeset, Params};
    use rustler::{Error, NifResult};

    #{modules}

    #{nifs}

    fn run(data: &str, params: &str, changeset: fn(&Params, &Params) -> Changeset) -> NifResult<String> {
        let data: Params = serde_json::from_str(data).map_err(bad_argument)?;
        let params: Params = serde_json::from_str(params).map_err(bad_argument)?;
        serde_json::to_string(changeset(&data, &params).errors()).map_err(bad_argument)
    }

    fn bad_argument(error: serde_json::Error) -> Error {
        Error::Term(Box::new(error.to_string()))
    }

    rustler::init!("Elixir.App.Data.UniversalChangeset.Native");
    """

    {:ok, source |> String.replace(~r/\n{3,}/, "\n\n") |> Transpile.format(Path.dirname(@rust_path))}
  end

  defp schema(module), do: module |> Module.split() |> List.last() |> Macro.underscore()
  defp rust_file(file), do: Path.rootname(file) <> ".rs"

  defp indent(text),
    do: text |> String.split("\n") |> Enum.map_join("\n", &if(&1 == "", do: "", else: "  " <> &1))
end
