defmodule App.Data.UniversalChangeset do
  @moduledoc """
  Runs a changeset function marked `@universal_changeset true` in Rust, the
  same Rust the desktop and mobile apps run, so every app casts and
  validates the same params with one implementation. See
  `priv/rust/README.md`.

      use App.Data.UniversalChangeset

      @universal_changeset true
      def changeset(post, params, options \\\\ []) do
        post
        |> cast(params, [:body])
        |> validate_required([:body])
      end

  The Ecto pipeline stays in the source as the template `mix app.rust`
  writes the Rust from, and is kept as `__universal_changeset_template__/4`.
  What `changeset/3` runs is `run/3`: the template runs for the typed
  changes, the constraints and the metadata the repo and `phoenix_ecto`
  read, then the raw params go to the Rust function, which casts and
  validates them as it does in the other apps, and its errors replace the
  template's. The changes the template made that the params did not
  supply, such as the author from the scope, go to the Rust as data, since
  the other apps set them the same way.

  Nothing here needs the Rust toolchain. The generated
  `App.Data.UniversalChangeset.Native` does, and `mix app.rust` writes it
  only while a function is marked.
  """

  # Generated by `mix app.rust`, and absent until a function is marked,
  # so it is only ever called through `apply`, which the compiler does
  # not check
  @native App.Data.UniversalChangeset.Native

  defmacro __using__(_opts) do
    quote do
      Module.register_attribute(__MODULE__, :universal_changeset, accumulate: false)
      Module.register_attribute(__MODULE__, :universal_changesets, accumulate: true)
      @on_definition App.Data.UniversalChangeset
      @before_compile App.Data.UniversalChangeset
    end
  end

  @doc false
  def __on_definition__(env, :def, name, args, guards, body) do
    if Module.get_attribute(env.module, :universal_changeset) do
      Module.delete_attribute(env.module, :universal_changeset)
      Module.put_attribute(env.module, :universal_changesets, {name, args, guards, body})
    end
  end

  def __on_definition__(_env, _kind, _name, _args, _guards, _body), do: :ok

  defmacro __before_compile__(env) do
    functions = env.module |> Module.get_attribute(:universal_changesets) |> Enum.reverse()
    marked = for {name, args, _guards, _body} <- functions, do: {name, length(args)}

    for {name, args, guards, body} <- functions do
      args = Enum.map(args, &without_default/1)
      arity = length(args)
      body = templates_call_templates(body, marked)

      quote do
        defoverridable [{unquote(name), unquote(arity)}]

        def unquote(name)(unquote_splicing(args)) do
          App.Data.UniversalChangeset.run(__MODULE__, unquote(name), [unquote_splicing(args)])
        end

        @doc false
        def __universal_changeset_template__(unquote(name), unquote_splicing(args))
            when unquote(guard(guards)),
            unquote(body)
      end
    end
  end

  # A template that calls another marked function must reach its template
  # and not its Rust
  defp templates_call_templates(body, marked) do
    Macro.prewalk(body, fn
      {:|>, _, [left, {name, meta, args}]} = node when is_atom(name) and is_list(args) ->
        if {name, length(args) + 1} in marked,
          do: {:__universal_changeset_template__, meta, [name, left | args]},
          else: node

      {name, meta, args} = node when is_atom(name) and is_list(args) ->
        if {name, length(args)} in marked,
          do: {:__universal_changeset_template__, meta, [name | args]},
          else: node

      node ->
        node
    end)
  end

  defp without_default({:\\, _, [arg, _default]}), do: arg
  defp without_default(arg), do: arg

  defp guard([]), do: true
  defp guard(guards), do: Enum.reduce(guards, &{:and, [], [&2, &1]})

  @doc """
  What a marked function runs: the template for the changes and the
  metadata, the Rust for the errors.
  """
  def run(module, function, [data, attrs | _] = args) do
    template = template(module, function, args)
    # credo:disable-for-next-line Credo.Check.Refactor.Apply
    cast = apply(@native, :cast, [module, function])
    fields = module.__schema__(:fields)

    {record, prior} =
      case data do
        %Ecto.Changeset{data: record, changes: changes} -> {record, changes}
        record -> {record, %{}}
      end

    # A change an earlier changeset made to a cast field is validated again
    # by Ecto when the params leave the field out, so it is a param here too
    params = prior |> Map.take(cast) |> params() |> Map.merge(params(attrs))

    # What the template set outside the cast, such as the author from the
    # scope, is data to the Rust, as it is in the other apps
    data = record |> Map.take(fields) |> Map.merge(template.changes |> Map.take(fields) |> Map.drop(cast))

    # credo:disable-for-lines:4 Credo.Check.Refactor.Apply
    errors =
      @native
      |> apply(:run, [module, function, Jason.encode!(data), Jason.encode!(params)])
      |> Jason.decode!()
      |> Enum.reverse()
      |> Enum.map(&error(&1, module))

    %{template | errors: errors, valid?: errors == []}
  end

  @doc """
  Calls the Ecto pipeline a marked function was written from, or the
  function itself when it is not marked. The parity test holds the Rust
  to what the template says.
  """
  def template(module, function, args) do
    if function_exported?(module, :__universal_changeset_template__, length(args) + 1) do
      apply(module, :__universal_changeset_template__, [function | args])
    else
      apply(module, function, args)
    end
  end

  # Ecto takes atom or string keys; the Rust takes the JSON object a form
  # posts, so the keys are strings
  defp params(attrs), do: Map.new(attrs, fn {key, value} -> {to_string(key), value} end)

  # An error as Ecto keeps it: the message template and its options in
  # Ecto's order. A field may be one a validation derives, such as
  # `body_confirmation`, which is not an atom until now
  defp error(%{"field" => field, "message" => message, "options" => options}, module) do
    field = String.to_atom(field)
    cast? = Enum.any?(options, &(&1 == ["validation", "cast"]))
    {field, {message, Enum.map(options, &option(&1, field, module, cast?))}}
  end

  defp option(["type", _type], field, module, true), do: {:type, module.__changeset__()[field]}

  defp option([key, value], _field, _module, _cast?) when key in ["validation", "kind", "type"],
    do: {String.to_atom(key), String.to_atom(value)}

  defp option([key, value], _field, _module, _cast?), do: {String.to_atom(key), value}
end
