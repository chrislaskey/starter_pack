defmodule App.ClientMigrations do
  @moduledoc """
  The SQLite migrations clients apply, exported from the migrations in
  `priv/repo/migrations`, see "Schema source of truth" in
  `docs/design/offline-sync.md`.

  `export/0` replays each migration, in order, against a scratch SQLite
  database and captures the statements the adapter ran, through the
  repo's query telemetry. The statements on synced tables, the sources of
  `App.Data.Sync.schemas/0`, become `priv/client_migrations/<version>_<name>.sql`;
  a migration that touches no synced table has no file. Statements on
  server-only tables, such as `users` and `app_purges`, never reach a
  client.

  `mix app.migrations` writes the files and `mix test` fails while one is
  missing or stale, the same check as `mix app.migrations --check`. The
  files are committed, so the clients build without Elixir. How a client
  applies them is in `priv/client_migrations/README.md`.
  """

  @dir "priv/client_migrations"
  @prefix [:app, :client_export]
  @repo_name :app_client_export

  # The table a statement is about, or nothing for the rest: transactions,
  # pragmas and the migrator's own bookkeeping.
  @table ~r/^\s*(?:CREATE|ALTER|DROP)\s+TABLE\s+(?:IF\s+(?:NOT\s+)?EXISTS\s+)?"([^"]+)"/i
  @index ~r/^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?"([^"]+)"\s+ON\s+"([^"]+)"/i
  @drop_index ~r/^\s*DROP\s+INDEX\s+(?:IF\s+EXISTS\s+)?"([^"]+)"/i

  @doc """
  The directory of the exported files, relative to the project root.
  """
  def dir, do: @dir

  @doc """
  The export as `%{file => sql}`, computed from the migrations.
  """
  def export do
    path = Ecto.Migrator.migrations_path(App.Repo)
    database = Path.join(System.tmp_dir!(), "app_client_export_#{System.unique_integer([:positive])}.db")
    handler = {__MODULE__, make_ref()}

    # Created first: two connections opening a new file at once fail with
    # "database is locked"
    :ok = App.Repo.__adapter__().storage_up(database: database)

    {:ok, pid} =
      App.Repo.start_link(
        name: @repo_name,
        database: database,
        pool_size: 2,
        log: false,
        telemetry_prefix: @prefix
      )

    :ok = :telemetry.attach(handler, @prefix ++ [:query], &__MODULE__.handle_query/4, self())
    conflicts = Code.get_compiler_option(:ignore_module_conflict)
    Code.put_compiler_option(:ignore_module_conflict, true)

    try do
      App.Repo
      |> Ecto.Migrator.migrations([path], dynamic_repo: @repo_name)
      |> Enum.reduce({%{}, %{}}, fn {_status, version, name}, {files, indexes} ->
        Ecto.Migrator.run(App.Repo, path, :up, to: version, dynamic_repo: @repo_name, log: false)
        {statements, indexes} = synced_statements(drain(), indexes)
        file = "#{version}_#{name}.sql"

        case statements do
          [] -> {files, indexes}
          statements -> {Map.put(files, file, render(file, statements)), indexes}
        end
      end)
      |> elem(0)
    after
      Code.put_compiler_option(:ignore_module_conflict, conflicts)
      :telemetry.detach(handler)
      Supervisor.stop(pid)
      for suffix <- ["", "-wal", "-shm"], do: File.rm(database <> suffix)
    end
  end

  @doc false
  def handle_query(_event, _measurements, %{query: query}, parent), do: send(parent, {@prefix, query})

  defp drain do
    receive do
      {@prefix, query} -> [query | drain()]
    after
      0 -> []
    end
  end

  # The statements on synced tables, with the indexes seen so far, so a
  # dropped index is placed by the table it was created on.
  defp synced_statements(statements, indexes) do
    synced = Enum.map(App.Data.Sync.schemas(), & &1.__schema__(:source))

    Enum.reduce(statements, {[], indexes}, fn statement, {kept, indexes} ->
      {table, indexes} = table_of(statement, indexes)
      if table in synced, do: {kept ++ [statement], indexes}, else: {kept, indexes}
    end)
  end

  defp table_of(statement, indexes) do
    cond do
      match = Regex.run(@table, statement) ->
        {Enum.at(match, 1), indexes}

      match = Regex.run(@index, statement) ->
        {Enum.at(match, 2), Map.put(indexes, Enum.at(match, 1), Enum.at(match, 2))}

      match = Regex.run(@drop_index, statement) ->
        {Map.get(indexes, Enum.at(match, 1)), indexes}

      true ->
        {nil, indexes}
    end
  end

  defp render(file, statements) do
    source = String.replace_suffix(file, ".sql", ".exs")

    "-- Generated by mix app.migrations from priv/repo/migrations/#{source}. Do not edit.\n" <>
      Enum.map_join(statements, "", &(String.trim(&1) <> ";\n"))
  end

  @doc """
  The files on disk that differ from the export: `{:missing, file}`,
  `{:stale, file}` and `{:orphan, file}`, a file no migration produces.
  """
  def check do
    export = export()
    on_disk = on_disk()

    missing = for file <- Map.keys(export), not Map.has_key?(on_disk, file), do: {:missing, file}
    stale = for {file, sql} <- export, Map.has_key?(on_disk, file), on_disk[file] != sql, do: {:stale, file}
    orphans = for file <- Map.keys(on_disk), not Map.has_key?(export, file), do: {:orphan, file}

    Enum.sort(missing ++ stale ++ orphans)
  end

  @doc """
  Writes every file of the export and removes the orphans. Returns what
  happened to each file.
  """
  def write do
    export = export()
    on_disk = on_disk()
    File.mkdir_p!(@dir)

    written =
      for {file, sql} <- export do
        if on_disk[file] == sql do
          {:unchanged, file}
        else
          File.write!(Path.join(@dir, file), sql)
          {:written, file}
        end
      end

    removed =
      for file <- Map.keys(on_disk), not Map.has_key?(export, file) do
        File.rm!(Path.join(@dir, file))
        {:removed, file}
      end

    Enum.sort(written ++ removed)
  end

  @doc """
  A problem of `check/0` as a sentence.
  """
  def describe({:missing, file}), do: "#{@dir}/#{file} is missing, run mix app.migrations"

  def describe({:stale, file}),
    do: "#{@dir}/#{file} is out of date with its migration, run mix app.migrations"

  def describe({:orphan, file}), do: "#{@dir}/#{file} has no migration, run mix app.migrations to remove it"

  defp on_disk do
    @dir
    |> Path.join("*.sql")
    |> Path.wildcard()
    |> Map.new(&{Path.basename(&1), File.read!(&1)})
  end
end
